#!/usr/bin/env bash
# Generate $LOCALNET_DATA/nodes/<role>/.env for all 5 roles (and state/cli/<who>.env for the CLIs) from:
#   scripts/localnet.env  (shared scalars)   state/contracts.json  state/subgraph.json
#   state/keys.env        (identities)
# Idempotent: safe to re-run after a contracts/subgraph redeploy. MOCK_* delay vars
# are deliberately NOT written here -- they live only in scripts/localnet.env and are
# exported by scripts/nodes.sh at launch (process env wins over .env), so they stay
# tunable in one place.
set -euo pipefail
ROOT=$(cd "$(dirname "$0")/.." && pwd)
source "$ROOT/scripts/localnet.env"
set -a; source "$STATE_DIR/keys.env"; set +a

CONTRACTS="$STATE_DIR/contracts.json"
SUBGRAPH="$STATE_DIR/subgraph.json"
[[ -f "$CONTRACTS" ]] || { echo "missing $CONTRACTS (run contracts-local/deploy-local.sh)" >&2; exit 1; }
[[ -f "$SUBGRAPH"  ]] || { echo "missing $SUBGRAPH (run subgraph/deploy-local.sh)" >&2; exit 1; }

GW=$(jq -r '.node_env.GOAT_GATEWAY_CONTRACT_ADDRESS' "$CONTRACTS")
SWAP=$(jq -r '.node_env.GOAT_SWAP_CONTRACT_ADDRESS' "$CONTRACTS")
GW_FROM=$(jq -r '.node_env.GOAT_GATEWAY_EVENT_FILTER_FROM' "$CONTRACTS")
GW_URL=$(jq -r '.node_env.GOAT_GATEWAY_EVENT_THE_GRAPH_URL' "$SUBGRAPH")
SWAP_URL=$(jq -r '.node_env.GOAT_SWAP_EVENT_THE_GRAPH_URL' "$SUBGRAPH")

[[ "$GW" =~ ^0x[0-9a-fA-F]{40}$ ]] || { echo "bad gateway address '$GW'" >&2; exit 1; }

# role -> key prefix in keys.env
declare -A PFX=( [committee_0]=C0 [committee_1]=C1 [operator_0]=OP0 [verifier_0]=VF0 [watchtower_0]=WT0 )

# Common header shared by every role .env.
common() {
  local role="$1"
  cat <<EOF
# nodes/$role/.env  -- GENERATED by scripts/gen-node-envs.sh. Do not hand-edit;
# change scripts/localnet.env or state/*.json and re-run the generator.
# TEST-ONLY keys. MOCK_* delays come from scripts/localnet.env via nodes.sh.
RUST_LOG=$RUST_LOG

# bitcoin (regtest) + goat (anvil)
BITCOIN_NETWORK=$BITCOIN_NETWORK
BTC_CHAIN_URL=$BTC_CHAIN_URL
GOAT_CHAIN_URL=$GOAT_CHAIN_URL

# the graph / contracts (read from state/*.json)
MIN_REQUIRED_VERIFIER=$MIN_REQUIRED_VERIFIER
GOAT_GATEWAY_CONTRACT_ADDRESS=$GW
GOAT_GATEWAY_EVENT_THE_GRAPH_URL=$GW_URL
GOAT_GATEWAY_EVENT_FILTER_FROM=$GW_FROM
GOAT_SWAP_CONTRACT_ADDRESS=$SWAP
GOAT_SWAP_EVENT_THE_GRAPH_URL=$SWAP_URL
GOAT_SWAP_EVENT_FILTER_FROM=0

# libp2p
PROTO_NAME=$PROTO_NAME
P2P_LISTEN_IP=$P2P_LISTEN_IP

# shared constants
GENESIS_SEQUENCER_COMMIT_TXID=$GENESIS_SEQUENCER_COMMIT_TXID
EOF
}

gen_committee() { # $1 role  $2 relayer(true/"")
  local role="$1" relayer="$2" p; p=${PFX[$role]}
  local secret_var="${p}_BITVM_SECRET"  peer_var="${p}_PEER_KEY"  gk_var="${p}_GOAT_PRIVATE_KEY"
  { common "$role"
    echo
    echo "# actor"
    echo "ACTOR=Committee"
    [[ -n "$relayer" ]] && { echo "ENABLE_RELAYER=true"; echo "ENABLE_UPDATE_SPV_CONTRACT=true"; }
    echo
    echo "# identity"
    echo "BITVM_SECRET=${!secret_var}"
    echo "PEER_KEY=${!peer_var}"
    echo "GOAT_PRIVATE_KEY=${!gk_var}"
  } > "$NODES_DIR/$role/.env"
}

gen_operator() {
  local role=operator_0 p=OP0
  { common "$role"
    echo
    echo "# actor"
    echo "ACTOR=Operator"
    echo "EXTERNAL_SOCKET_ADDR=127.0.0.1:$((RPC_PORT_BASE+2))"
    echo
    echo "# identity"
    echo "BITVM_SECRET=${OP0_BITVM_SECRET}"
    echo "PEER_KEY=${OP0_PEER_KEY}"
    echo "GOAT_PRIVATE_KEY=${OP0_GOAT_PRIVATE_KEY}"
    echo
    echo "# proof / soldering (mock)"
    echo "GOAT_PROOF_BUILD_URL=$GOAT_PROOF_BUILD_URL"
    echo "SOLDERING_PROOF_PAYLOAD_STORE_PATH=$SOLDERING_PROOF_PAYLOAD_STORE_PATH"
    echo "OPERATOR_VK_HASH=$OPERATOR_VK_HASH"
    echo "OPERATOR_ZKM_VERSION=$OPERATOR_ZKM_VERSION"
    echo "ZKM_IMM_WRAP_VK=$ZKM_IMM_WRAP_VK"
    echo "WATCHTOWER_PROOF_WAIT_SECS=$WATCHTOWER_PROOF_WAIT_SECS"
    echo "OPERATOR_PROOF_WAIT_SECS=$OPERATOR_PROOF_WAIT_SECS"
    echo "ENABLE_BABE_SETUP_STATE_CLEANUP=true"
  } > "$NODES_DIR/$role/.env"
}

gen_verifier() {
  local role=verifier_0 p=VF0
  { common "$role"
    echo
    echo "# actor"
    echo "ACTOR=Verifier"
    echo
    echo "# identity (GOAT key required: Challenge tx embeds the verifier GOAT addr in OP_RETURN)"
    echo "BITVM_SECRET=${VF0_BITVM_SECRET}"
    echo "PEER_KEY=${VF0_PEER_KEY}"
    echo "GOAT_PRIVATE_KEY=${VF0_GOAT_PRIVATE_KEY}"
    echo
    echo "# proof / soldering (mock)"
    echo "SOLDERING_PROOF_PAYLOAD_STORE_PATH=$SOLDERING_PROOF_PAYLOAD_STORE_PATH"
    echo "OPERATOR_VK_HASH=$OPERATOR_VK_HASH"
    echo "OPERATOR_ZKM_VERSION=$OPERATOR_ZKM_VERSION"
    echo "ZKM_IMM_WRAP_VK=$ZKM_IMM_WRAP_VK"
    echo "ENABLE_BABE_SETUP_STATE_CLEANUP=true"
  } > "$NODES_DIR/$role/.env"
}

gen_watchtower() {
  local role=watchtower_0 p=WT0
  { common "$role"
    echo
    echo "# actor"
    echo "ACTOR=Watchtower"
    echo
    echo "# identity (GOAT key not required by code, provided for convenience)"
    echo "BITVM_SECRET=${WT0_BITVM_SECRET}"
    echo "PEER_KEY=${WT0_PEER_KEY}"
    echo "GOAT_PRIVATE_KEY=${WT0_GOAT_PRIVATE_KEY}"
    echo
    echo "# proof (mock)"
    echo "GOAT_PROOF_BUILD_URL=$GOAT_PROOF_BUILD_URL"
    echo "WATCHTOWER_PROOF_WAIT_SECS=$WATCHTOWER_PROOF_WAIT_SECS"
  } > "$NODES_DIR/$role/.env"
}

mkdir -p "$NODES_DIR"/{committee_0,committee_1,operator_0,verifier_0,watchtower_0} "$STATE_DIR/cli"
gen_committee committee_0 true
gen_committee committee_1 ""
gen_operator
gen_verifier
gen_watchtower

chmod 600 "$NODES_DIR"/*/.env

# CLI identities for pegin-request / pegout / challenge (sourced by the e2e flows): the user,
# the operator and the verifier. Same test-only keys as the nodes.
gen_cli() { # $1 file  $2 key prefix
  { echo "# $STATE_DIR/cli/$1 -- GENERATED by scripts/gen-node-envs.sh (TEST-ONLY keys)"
    echo "export GOAT_CHAIN_URL=$GOAT_CHAIN_URL"
    echo "export GOAT_GATEWAY_CONTRACT_ADDRESS=$GW"
    echo "export BITCOIN_NETWORK=$BITCOIN_NETWORK"
    local s="${2}_BITVM_SECRET" k="${2}_GOAT_PRIVATE_KEY" a="${2}_GOAT_ADDRESS"
    echo "export BITVM_SECRET=${!s}"
    echo "export GOAT_PRIVATE_KEY=${!k}"
    echo "export GOAT_ADDRESS=${!a}"
  } > "$STATE_DIR/cli/$1"
}
gen_cli user.env USER0; gen_cli operator.env OP0; gen_cli verifier.env VF0
chmod 600 "$STATE_DIR"/cli/*.env
echo "Generated .env for: committee_0 committee_1 operator_0 verifier_0 watchtower_0"
echo "  gateway=$GW  filter_from=$GW_FROM"
echo "  gateway_subgraph=$GW_URL"
