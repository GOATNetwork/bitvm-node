#!/usr/bin/env bash
# Deploy the BitVM2 Gateway subgraph to the localnet graph-node.
# Idempotent: copies the subgraph sources to $LOCALNET_DATA/subgraph/gateway (the checkout stays
# untouched), regenerates the ABI from the forge build, patches the manifest with the gateway
# address + start block from state/contracts.json, runs npm ci / codegen / build / create / deploy
# inside the pinned node container (host needs only docker), and writes state/subgraph.json.
#
# Re-run this AFTER every contracts-local/deploy-local.sh run (addresses + start block change).
# Overrides (env): SUBGRAPH_NAME, VERSION_LABEL
set -euo pipefail
ROOT=$(cd "$(dirname "$0")/.." && pwd)
source "$ROOT/scripts/localnet.env"

SG_SRC=$ROOT/subgraph/gateway
SG=$LOCALNET_DATA/subgraph/gateway
CONTRACTS_JSON=$STATE_DIR/contracts.json
ABI_SRC=$LOCALNET_DATA/forge/out/Gateway.sol/GatewayUpgradeable.json
VERSION_LABEL=${VERSION_LABEL:-v$(date +%Y%m%d-%H%M%S)}
NETWORK=goat-local

echo "[deploy-local] reading $CONTRACTS_JSON"
GW=$(jq -r '.addresses.gateway_proxy' "$CONTRACTS_JSON")
SB=$(jq -r '.subgraph_start_block' "$CONTRACTS_JSON")
echo "[deploy-local] gateway_proxy=$GW startBlock=$SB name=$SUBGRAPH_NAME"

[ -f "$ABI_SRC" ] || { echo "[deploy-local] ERROR: $ABI_SRC not found (run contracts-local/deploy-local.sh first)" >&2; exit 1; }

echo "[deploy-local] staging sources in $SG"
mkdir -p "$SG"
for f in schema.graphql subgraph.yaml networks.json package.json package-lock.json tsconfig.json src abis; do
  rm -rf "$SG/$f"; cp -r "$SG_SRC/$f" "$SG/"
done
rm -rf "$SG/build" "$SG/generated"
# node_modules is kept between runs; it is rebuilt when the lock file changed.
if [ -f "$SG/node_modules/.package-lock.json" ] && cmp -s "$SG_SRC/package-lock.json" "$SG/.installed-lock.json"; then
  NEED_INSTALL=0
else
  NEED_INSTALL=1
fi

echo "[deploy-local] regenerating ABI from the forge build"
python3 -c "import json;json.dump(json.load(open('$ABI_SRC'))['abi'], open('$SG/abis/GatewayUpgradeable.json','w'), indent=2)"

echo "[deploy-local] patching subgraph.yaml + networks.json"
python3 - "$SG/subgraph.yaml" "$GW" "$SB" "$NETWORK" <<'PY'
import re, sys
path, gw, sb, net = sys.argv[1:5]
s = open(path).read()
s = re.sub(r'network: \S+', f'network: {net}', s, count=1)
s = re.sub(r'address: "0x[0-9a-fA-F]{40}"', f'address: "{gw}"', s, count=1)
s = re.sub(r'startBlock: \d+', f'startBlock: {sb}', s, count=1)
open(path, 'w').write(s)
PY
python3 - "$SG/networks.json" "$GW" "$SB" "$NETWORK" <<'PY'
import json, sys
path, gw, sb, net = sys.argv[1:5]
json.dump({net: {"GatewayUpgradeable": {"address": gw, "startBlock": int(sb)}}}, open(path, 'w'), indent=2)
PY

echo "[deploy-local] graph-cli in the node container (install=$NEED_INSTALL)"
docker run --rm --network host -u "$LOCALNET_UID:$LOCALNET_GID" \
  -v "$SG:/sg" -w /sg -e HOME=/sg/.home -e npm_config_cache=/sg/.npm \
  -e NEED_INSTALL="$NEED_INSTALL" -e GRAPH_ADMIN="$GRAPH_ADMIN" -e GRAPH_IPFS="$GRAPH_IPFS" \
  -e SUBGRAPH_NAME="$SUBGRAPH_NAME" -e VERSION_LABEL="$VERSION_LABEL" \
  "$NODE_IMAGE" sh -ec '
    if [ "$NEED_INSTALL" = 1 ]; then npm ci --no-audit --no-fund --loglevel=error && cp package-lock.json .installed-lock.json; fi
    G=./node_modules/.bin/graph
    $G codegen subgraph.yaml
    $G build subgraph.yaml
    $G create --node "$GRAPH_ADMIN" "$SUBGRAPH_NAME" || true
    $G deploy --node "$GRAPH_ADMIN" --ipfs "$GRAPH_IPFS" --version-label "$VERSION_LABEL" "$SUBGRAPH_NAME" subgraph.yaml'

QUERY_URL="$GRAPH_QUERY_BASE/subgraphs/name/$SUBGRAPH_NAME"
echo "[deploy-local] writing $STATE_DIR/subgraph.json"
python3 - "$STATE_DIR/subgraph.json" "$SUBGRAPH_NAME" "$QUERY_URL" "$GW" "$SB" "$VERSION_LABEL" "$GRAPH_ADMIN" "$GRAPH_IPFS" <<'PY'
import json, sys, datetime
path, name, qurl, gw, sb, ver, admin, ipfs = sys.argv[1:9]
doc = {
  "_note": "TEST-ONLY local Gateway subgraph on the localnet graph-node. Generated by localnet/subgraph/deploy-local.sh.",
  "generated_at": datetime.datetime.now(datetime.timezone.utc).isoformat(),
  "subgraph_name": name,
  "network": "goat-local",
  "gateway_address": gw,
  "start_block": int(sb),
  "version_label": ver,
  "graph_admin": admin,
  "graph_ipfs": ipfs,
  "query_url": qurl,
  "node_env": {
    "GOAT_GATEWAY_EVENT_THE_GRAPH_URL": qurl,
    "GOAT_SWAP_EVENT_THE_GRAPH_URL": qurl
  }
}
open(path, 'w').write(json.dumps(doc, indent=2) + "\n")
print(json.dumps(doc, indent=2))
PY
chmod 600 "$STATE_DIR/subgraph.json" || true
echo "[deploy-local] DONE. Query endpoint: $QUERY_URL"
echo "[deploy-local] health: curl -s -XPOST -d '{\"query\":\"{indexingStatuses{synced health chains{latestBlock{number}}}}\"}' -H 'content-type: application/json' $GRAPH_INDEX/graphql"
