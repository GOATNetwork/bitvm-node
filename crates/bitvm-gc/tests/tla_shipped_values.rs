//! Synchronizes the finite timing model with Rust's default network parameters.
use bitcoin::Network;
use bitvm_gc::timelocks::{default_timelock_config, protocol_timing_budget};
use std::path::PathBuf;

const NETWORKS: [(&str, Network); 4] = [
    ("Bitcoin", Network::Bitcoin),
    ("Testnet4", Network::Testnet4),
    ("Signet", Network::Signet),
    ("Regtest", Network::Regtest),
];

fn record(name: &str, value: impl Fn(Network) -> u32) -> String {
    let fields: Vec<_> = NETWORKS
        .iter()
        .map(|(label, network)| format!("{label} |-> {}", value(*network)))
        .collect();
    format!("{name} == [{}]\n", fields.join(", "))
}

fn render() -> String {
    let tl = default_timelock_config;
    let mut out = String::from(
        "---- MODULE ShippedTimelockValues ----\n\
         \\* Generated by tests/tla_shipped_values.rs; regenerate with make tla-values.\n\
         EXTENDS Integers\n\n\
         Networks == {\"Bitcoin\", \"Testnet4\", \"Signet\", \"Regtest\"}\n\n",
    );
    out += &record("ConnectorA", |n| tl(n).connector_a);
    out += &record("ProverConnector", |n| tl(n).prover_connector);
    out += &record("ConnectorD", |n| tl(n).connector_d);
    out += &record("WatchtowerChallenge", |n| tl(n).watchtower_challenge);
    out += &record("OperatorAck", |n| tl(n).operator_ack);
    out += &record("OperatorCommit", |n| tl(n).operator_commit);
    out += &record("ConnectorF", |n| tl(n).connector_f);
    let action_window = |n| {
        let budget = protocol_timing_budget(n);
        budget
            .reaction_blocks
            .saturating_add(budget.inclusion_blocks)
            .saturating_add(budget.safety_blocks)
    };
    out += &record("ActionWindow", action_window);
    out += &record("DisproveWindow", |n| {
        action_window(n).saturating_add(protocol_timing_budget(n).inclusion_blocks)
    });
    out += "\n====\n";
    out
}

#[test]
fn shipped_timelock_values_tla_is_in_sync() {
    let path =
        PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../audit/tla/ShippedTimelockValues.tla");
    let rendered = render();
    if std::env::var_os("UPDATE_TLA_VALUES").is_some() {
        std::fs::write(&path, rendered).expect("write ShippedTimelockValues.tla");
        return;
    }
    assert_eq!(
        std::fs::read_to_string(&path).expect("read ShippedTimelockValues.tla"),
        rendered,
        "timing values changed; run make tla-values, then make tla"
    );
}
