//! Keeps `audit/tla/specs/crates/bitvm-gc/ShippedTimelockValues.tla` in sync with the shipped timing
//! constants. The TLA+ specs read every per-network timelock, timing-budget and
//! SPV-depth value from that module, so a spec can never check a stale number.
//!
//! The test fails when the file differs from what the Rust constants render to.
//! Regenerate it with `make tla-values` (`UPDATE_TLA_VALUES=1 cargo test -p bitvm-gc
//! --test tla_shipped_values`).

use bitcoin::Network;
use bitvm_gc::timelocks::{
    default_pegin_abandon_buffer_blocks, default_timelock_config, estimated_block_interval_secs,
    protocol_timing_budget,
};
use std::path::PathBuf;

const NETWORKS: [(&str, Network); 4] = [
    ("Bitcoin", Network::Bitcoin),
    ("Testnet4", Network::Testnet4),
    ("Signet", Network::Signet),
    ("Regtest", Network::Regtest),
];

fn record(name: &str, doc: &str, value: impl Fn(Network) -> i64) -> String {
    let fields: Vec<String> =
        NETWORKS.iter().map(|(label, network)| format!("{label} |-> {}", value(*network))).collect();
    format!("\\* {doc}\n{name} == [{}]\n", fields.join(", "))
}

fn render() -> String {
    let tl = default_timelock_config;
    let budget = protocol_timing_budget;
    let mut out = String::from(
        "---- MODULE ShippedTimelockValues ----\n\
         (* GENERATED by crates/bitvm-gc/tests/tla_shipped_values.rs from the    *)\n\
         (* shipped constants - do not edit. Regenerate with `make tla-values`.  *)\n\
         (* The test fails in CI when this file and the Rust constants differ.   *)\n\
         EXTENDS Integers\n\n\
         Networks == {\"Bitcoin\", \"Testnet4\", \"Signet\", \"Regtest\"}\n\n\
         \\* ---- CSV timelocks (crates/bitvm-gc/src/timelocks.rs default_timelock_config)\n",
    );
    out += &record("ConnectorZ", "Peg-In deposit, user cancel leaf (T0)", |n| tl(n).connector_z.into());
    out += &record("ConnectorA", "Kickoff connector A: Take1 vs Challenge", |n| tl(n).connector_a.into());
    out += &record("ProverConnector", "Verifier-Assert -> Disprove (WronglyChallenged window)", |n| {
        tl(n).prover_connector.into()
    });
    out += &record("ConnectorD", "Operator-Assert -> Take2", |n| tl(n).connector_d.into());
    out += &record("WatchtowerChallenge", "WCInit -> watchtower challenge timeout", |n| {
        tl(n).watchtower_challenge.into()
    });
    out += &record("OperatorAck", "WCInit -> NACK", |n| tl(n).operator_ack.into());
    out += &record("OperatorCommit", "WCInit -> Commit-Timeout", |n| tl(n).operator_commit.into());
    out += &record("ConnectorF", "WCInit -> Take2 (connector F)", |n| tl(n).connector_f.into());
    out += "\n\\* ---- local timing budget (timelocks.rs protocol_timing_budget)\n";
    out += &record("EvidenceConfirmations", "evidence depth before it is used", |n| {
        budget(n).evidence_confirmations.into()
    });
    out += &record("ReactionBlocks", "discovery, propagation, scheduling, signing", |n| {
        budget(n).reaction_blocks.into()
    });
    out += &record("WatchtowerProofBlocks", "P99 watchtower proof preparation", |n| {
        budget(n).watchtower_proof_blocks.into()
    });
    out += &record("InclusionBlocks", "blocks to get a tx included, incl. fee bumping", |n| {
        budget(n).inclusion_blocks.into()
    });
    out += &record("SafetyBlocks", "reorg and transient failure allowance", |n| {
        budget(n).safety_blocks.into()
    });
    out += "ActionWindow == [n \\in Networks |-> ReactionBlocks[n] + InclusionBlocks[n] + SafetyBlocks[n]]\n";
    out += "\n\\* ---- other shipped defaults\n";
    out += &record("PeginAbandonBufferBlocks", "B: peg-in abandon buffer after T0", |n| {
        default_pegin_abandon_buffer_blocks(n).into()
    });
    out += &record("BtcBlockConfirms", "SPV updater lag: posts up to tip - this (util::get_btc_block_confirms)", |n| {
        util::get_btc_block_confirms(n).into()
    });
    out += &record("BlockIntervalSecs", "estimated block interval", estimated_block_interval_secs);
    out += "\n====\n";
    out
}

#[test]
fn shipped_timelock_values_tla_is_in_sync() {
    let path = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../../audit/tla/specs/crates/bitvm-gc/ShippedTimelockValues.tla");
    let rendered = render();
    if std::env::var_os("UPDATE_TLA_VALUES").is_some() {
        std::fs::write(&path, &rendered).expect("write ShippedTimelockValues.tla");
        return;
    }
    let current = std::fs::read_to_string(&path).unwrap_or_default();
    assert!(
        current == rendered,
        "{} is stale: the shipped timing constants changed. Run `make tla-values` and re-run `make tla`.",
        path.display()
    );
}
